# characters of subgroups (1-dim):
# psi5 on C5: order-5 character; on S3: the sign character sgn (S3 ~ Sym3); on C5 in D5 etc.
z5=cmath.exp(2j*math.pi/5)
def c5_log(x):  # power of c5gen
    g=e
    for k in range(5):
        if g==x: return k
        g=mul(g,c5gen)
    return None
def psi5(x,j=1): return z5**(c5_log(x)*j)

# sgn on S3: even perms of the triangle {0,1,2} -> +1, transposition-type -> -1.
# In our S3 (acting on {0,1,2} x {3,4}), elements are (rot^k) and (rot^k * t).
S3rot={e,r3,mul(r3,r3)}
def sgnS3(x): return 1 if x in S3rot else -1

# induced character of Ind_H^G(chi) evaluated at g: (1/|H|) sum_{x in G, x^-1 g x in H} chi(x^-1 g x)
def induced_char(G,H,chi,g):
    s=0
    for x in G:
        y=mul(mul(inv(x),g),x)
        if y in H: s+=chi(y)
    return s/len(H)

Hset_C5=set(C5); Hset_S3=set(S3)
def indC5(g): return induced_char(A5,Hset_C5,lambda y: psi5(y,1),g)
def indS3(g): return induced_char(A5,Hset_S3,sgnS3,g)

# D5 irreducible characters (order 10): two 1-dims (triv, sgn_D5), two 2-dims (rho_1, rho_2)
