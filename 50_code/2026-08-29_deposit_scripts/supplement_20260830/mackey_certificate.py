def is_even(p):
    n=len(p); seen=[False]*n; parity=0
    for i in range(n):
        if not seen[i]:
            j=i; c=0
            while not seen[j]: seen[j]=True; j=p[j]; c+=1
            parity ^= (c-1)&1
    return parity==0

A5=[p for p in permutations(range(5)) if is_even(p)]
def mul(a,b): return tuple(a[b[i]] for i in range(5))
def inv(a):
    r=[0]*5
    for i,v in enumerate(a): r[v]=i
    return tuple(r)
e=tuple(range(5))

